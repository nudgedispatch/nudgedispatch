#!/usr/bin/env python3
"""Build the in-app ride alert sound: an original two-tone chime, then a voice saying "You've got a ride".

Chime: synthesized here (sine partials + exponential decay envelope). Voice: Kokoro-82M TTS
(Apache-2.0 model and voices, runs locally via kokoro-onnx; no paid API). Output is loudness
normalized (EBU R128, -14 LUFS integrated, -1 dBTP) so it is clearly audible in a car.

Usage (from the repo root):
  python3 scripts/sounds/make-ride-alert.py --kokoro-dir /path/to/kokoro-model-files
Writes app/sounds/source/{chime,voice}.wav, app/sounds/ride-alert.{mp3,ogg}, and
app/sounds/ride-alert-audio.js (base64 modules the Worker serves at /sounds/ride-alert.*).
If --kokoro-dir is omitted, the committed app/sounds/source/voice.wav is reused.
"""
import argparse, base64, os, subprocess, wave
import numpy as np

SR = 24000
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
SRC = os.path.join(ROOT, "app", "sounds", "source")
OUT = os.path.join(ROOT, "app", "sounds")


def write_wav(path, samples):
    pcm = (np.clip(samples, -1, 1) * 32767).astype("<i2")
    with wave.open(path, "wb") as w:
        w.setnchannels(1); w.setsampwidth(2); w.setframerate(SR); w.writeframes(pcm.tobytes())


def read_wav(path):
    with wave.open(path, "rb") as w:
        assert w.getframerate() == SR and w.getnchannels() == 1
        return np.frombuffer(w.readframes(w.getnframes()), dtype="<i2").astype(np.float32) / 32767


def note(freq, dur, start, total):
    t = np.arange(int(dur * SR)) / SR
    attack = np.minimum(t / 0.006, 1.0)
    env = attack * np.exp(-t * 7.5)
    tone = np.sin(2 * np.pi * freq * t) + 0.35 * np.sin(2 * np.pi * freq * 2 * t) + 0.12 * np.sin(2 * np.pi * freq * 3.01 * t)
    out = np.zeros(total, dtype=np.float32)
    i = int(start * SR)
    seg = (tone * env).astype(np.float32)
    out[i:i + len(seg)] += seg[: total - i]
    return out


def chime():
    # Rising major sixth (E5 -> C#6), bell-like partials, ~0.55 s.
    total = int(0.55 * SR)
    s = note(659.25, 0.5, 0.0, total) + note(1108.73, 0.42, 0.13, total)
    return (s / np.max(np.abs(s)) * 0.8).astype(np.float32)


def voice(kokoro_dir):
    from kokoro_onnx import Kokoro
    k = Kokoro(os.path.join(kokoro_dir, "kokoro-v1.0.onnx"), os.path.join(kokoro_dir, "voices-v1.0.bin"))
    samples, sr = k.create("You've got a ride!", voice="af_heart", speed=1.12, lang="en-us")
    assert sr == SR
    s = np.asarray(samples, dtype=np.float32)
    idx = np.where(np.abs(s) > 0.01)[0]  # trim silence
    s = s[max(idx[0] - int(0.02 * SR), 0): idx[-1] + int(0.06 * SR)]
    return s / np.max(np.abs(s)) * 0.9


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--kokoro-dir", default="")
    a = ap.parse_args()
    os.makedirs(SRC, exist_ok=True)
    c = chime(); write_wav(os.path.join(SRC, "chime.wav"), c)
    vpath = os.path.join(SRC, "voice.wav")
    if a.kokoro_dir:
        write_wav(vpath, voice(a.kokoro_dir))
    v = read_wav(vpath)
    gap = np.zeros(int(0.06 * SR), dtype=np.float32)
    mix = np.concatenate([c, gap, v, np.zeros(int(0.05 * SR), dtype=np.float32)])
    combined = os.path.join(SRC, "ride-alert-mix.wav")
    write_wav(combined, mix)
    # Gentle compression so the voice stays loud next to the chime peaks, then two-pass linear loudnorm.
    pre = os.path.join(SRC, "ride-alert-pre.wav")
    subprocess.run(["ffmpeg", "-y", "-loglevel", "error", "-i", combined, "-af", "acompressor=threshold=-20dB:ratio=4:attack=3:release=60:makeup=2", pre], check=True)
    os.replace(pre, combined)
    # Two-pass linear loudnorm: measure first, then apply one gain (keeps the chime/voice balance).
    import json as _json
    probe = subprocess.run(["ffmpeg", "-hide_banner", "-i", combined, "-af", "loudnorm=I=-14:TP=-1:LRA=11:print_format=json", "-f", "null", "-"], capture_output=True, text=True).stderr
    m = _json.loads(probe[probe.rindex("{"):probe.rindex("}") + 1])
    norm = ("loudnorm=I=-14:TP=-1:LRA=11:linear=true:measured_I={input_i}:measured_TP={input_tp}:measured_LRA={input_lra}:measured_thresh={input_thresh}:offset={target_offset}").format(**m)
    subprocess.run(["ffmpeg", "-y", "-loglevel", "error", "-i", combined, "-af", norm, "-ar", "44100", "-ac", "1", "-c:a", "libmp3lame", "-b:a", "64k", os.path.join(OUT, "ride-alert.mp3")], check=True)
    subprocess.run(["ffmpeg", "-y", "-loglevel", "error", "-i", combined, "-af", norm, "-ar", "48000", "-ac", "1", "-c:a", "libopus", "-b:a", "48k", os.path.join(OUT, "ride-alert.ogg")], check=True)
    os.remove(combined)
    mp3 = base64.b64encode(open(os.path.join(OUT, "ride-alert.mp3"), "rb").read()).decode()
    ogg = base64.b64encode(open(os.path.join(OUT, "ride-alert.ogg"), "rb").read()).decode()
    with open(os.path.join(OUT, "ride-alert-audio.js"), "w") as f:
        f.write("// Generated by scripts/sounds/make-ride-alert.py. Do not edit by hand.\n")
        f.write("// In-app ride alert: original chime + \"You've got a ride\" (Kokoro TTS, Apache-2.0).\n")
        f.write(f'export const RIDE_ALERT_MP3_B64 = "{mp3}";\n')
        f.write(f'export const RIDE_ALERT_OGG_B64 = "{ogg}";\n')
    print("seconds", round(len(mix) / SR, 2))


if __name__ == "__main__":
    main()
